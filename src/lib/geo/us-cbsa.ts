// Core-Based Statistical Areas (CBSAs) and the counties that make them up —
// the Census Bureau's July 2023 delineation, converted from its published
// `list1_2023.xlsx` (see scripts/README or the issue #313 thread for the
// source URL). Regenerated only when the Census republishes, which is
// roughly every few years.
//
// This is NOT the app's own `metros` table (src/db/schema.ts). That one is a
// hand-curated label attached to city-level places, used for grouping the
// user's own data (the life timeline's "Metro area" grouping merges Reston
// and Tysons Corner into "Washington DC" through it). This file is standard
// federal geography, used to draw map polygons — a different thing that
// happens to share the word "metro".
//
// Committed as structured text rather than fetched at runtime, per #163:
// it's official, published, highly repetitive data, so git deltas it well —
// the same reasoning that puts TopoJSON in the repo. It is only a
// *mapping*; the metro polygons themselves are never stored, they're
// dissolved from county geometry at render time with `topojson.merge`.
//
// 935 CBSAs over 1,915 counties. 43 of the 393 metropolitan areas span more
// than one state (Washington DC, New York, Chicago, Boston, Charlotte...),
// which is why the map's metro view is a whole-country tier rather than
// something you drill into from a single state — a state-scoped expansion
// would slice those areas at the state line.

