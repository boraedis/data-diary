/** county FIPS -> CBSA code, inverted from CBSA_AREAS on first use. A county
 * belongs to at most one CBSA, so this is a plain lookup rather than a
 * multimap. */
let cbsaByCounty: Map<string, string> | null = null;

export function cbsaCodeForCounty(countyFips: string): string | null {
  if (!cbsaByCounty) {
    cbsaByCounty = new Map();
    for (const [code, area] of Object.entries(CBSA_AREAS)) {
      for (const fips of area.counties) cbsaByCounty.set(fips, code);
    }
  }
  return cbsaByCounty.get(countyFips) ?? null;
}
